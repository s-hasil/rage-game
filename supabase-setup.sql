-- This creates player profiles, saved runs, and a public global leaderboard.

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text not null unique,
  created_at timestamptz not null default now(),
  constraint username_length check (char_length(username) between 3 and 18)
);

create table if not exists public.scores (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  score integer not null check (score between 0 and 1000000),
  created_at timestamptz not null default now()
);

create index if not exists scores_user_score_idx on public.scores(user_id, score desc);
create index if not exists scores_score_idx on public.scores(score desc);

alter table public.profiles enable row level security;
alter table public.scores enable row level security;

drop policy if exists "Profiles are publicly readable" on public.profiles;
create policy "Profiles are publicly readable"
on public.profiles for select using (true);

drop policy if exists "Players can create their own profile" on public.profiles;
create policy "Players can create their own profile"
on public.profiles for insert with check (auth.uid() = id);

drop policy if exists "Players can update their own profile" on public.profiles;
create policy "Players can update their own profile"
on public.profiles for update using (auth.uid() = id) with check (auth.uid() = id);

drop policy if exists "Scores are publicly readable" on public.scores;
create policy "Scores are publicly readable"
on public.scores for select using (true);

drop policy if exists "Players can submit their own scores" on public.scores;
create policy "Players can submit their own scores"
on public.scores for insert with check (auth.uid() = user_id);

-- Create a profile automatically when a player registers.
create or replace function public.handle_new_voidrun_player()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  chosen_name text;
begin
  chosen_name := left(coalesce(
    nullif(trim(new.raw_user_meta_data ->> 'username'), ''),
    'Pilot' || substr(new.id::text, 1, 6)
  ), 18);

  -- Keep names unique even when two people choose the same pilot name.
  if exists (select 1 from public.profiles where lower(username) = lower(chosen_name)) then
    chosen_name := left(chosen_name, 11) || '-' || substr(new.id::text, 1, 6);
  end if;

  insert into public.profiles (id, username)
  values (new.id, chosen_name)
  on conflict (id) do nothing;

  return new;
end;
$$;

drop trigger if exists on_voidrun_player_created on auth.users;
create trigger on_voidrun_player_created
after insert on auth.users
for each row execute procedure public.handle_new_voidrun_player();

-- Public leaderboard: each player's best submitted run.
create or replace view public.leaderboard
with (security_invoker = true)
as
select
  p.id as user_id,
  p.username,
  max(s.score)::integer as high_score,
  max(s.created_at) as last_played
from public.profiles p
join public.scores s on s.user_id = p.id
group by p.id, p.username;

grant select on public.leaderboard to anon, authenticated;
grant select on public.profiles to anon, authenticated;
grant select on public.scores to anon, authenticated;
grant insert on public.scores to authenticated;
grant insert, update on public.profiles to authenticated;


-- Player profile pictures (publicly readable images; each user can manage only their own folder).
alter table public.profiles add column if not exists avatar_url text;

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('avatars', 'avatars', true, 2097152, array['image/png','image/jpeg','image/webp'])
on conflict (id) do update set public = true, file_size_limit = 2097152,
  allowed_mime_types = array['image/png','image/jpeg','image/webp'];

drop policy if exists "Avatar images are publicly readable" on storage.objects;
create policy "Avatar images are publicly readable"
on storage.objects for select using (bucket_id = 'avatars');

drop policy if exists "Players upload their own avatar" on storage.objects;
create policy "Players upload their own avatar"
on storage.objects for insert to authenticated
with check (bucket_id = 'avatars' and (storage.foldername(name))[1] = auth.uid()::text);

drop policy if exists "Players update their own avatar" on storage.objects;
create policy "Players update their own avatar"
on storage.objects for update to authenticated
using (bucket_id = 'avatars' and (storage.foldername(name))[1] = auth.uid()::text)
with check (bucket_id = 'avatars' and (storage.foldername(name))[1] = auth.uid()::text);
